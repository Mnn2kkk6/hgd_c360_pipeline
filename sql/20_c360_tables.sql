-- 3. QUEUE / SYNC CONTROL / SYNC LOG
-------------------------------------------------------------------------------
CREATE TABLE C360_QUEUE (
    ID          NUMBER GENERATED ALWAYS AS IDENTITY,
    MA_CD       VARCHAR2(30) NOT NULL,
    ACTION      CHAR(1),
    CREATED_AT  TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT PK_C360_QUEUE PRIMARY KEY (ID)
)
/
CREATE TABLE C360_QUEUE_SNAP (          -- snapshot ID queue tại thời điểm bắt đầu Full Load
    ID NUMBER NOT NULL,
    CONSTRAINT PK_C360_QUEUE_SNAP PRIMARY KEY (ID)
)
/
CREATE GLOBAL TEMPORARY TABLE C360_TMP_IDS (ID NUMBER NOT NULL) ON COMMIT DELETE ROWS
/
CREATE GLOBAL TEMPORARY TABLE C360_TMP_KEYS (MA_CD VARCHAR2(30) NOT NULL) ON COMMIT DELETE ROWS
/
CREATE TABLE C360_SYNC_CONTROL (
    JOB_NAME        VARCHAR2(30) NOT NULL,
    PAUSE_FLAG      NUMBER(1)    DEFAULT 0 NOT NULL,   -- 1 = Full Load đang chạy, NRT phải bỏ qua
    STATUS          VARCHAR2(20) DEFAULT 'IDLE' NOT NULL,
    LAST_NRT_RUN    DATE,
    LAST_FULL_LOAD  DATE,
    NOTE            VARCHAR2(500),
    CONSTRAINT PK_C360_SYNC_CONTROL PRIMARY KEY (JOB_NAME)
)
/
INSERT INTO C360_SYNC_CONTROL (JOB_NAME) VALUES ('C360')
/
COMMIT
/
CREATE TABLE C360_SYNC_LOG (
    LOG_ID        NUMBER GENERATED ALWAYS AS IDENTITY,
    JOB_TYPE      VARCHAR2(20) NOT NULL,        -- NRT | FULL | MAP | DATAMART
    START_TIME    TIMESTAMP    NOT NULL,
    END_TIME      TIMESTAMP,
    QUEUE_ROWS    NUMBER,
    KEYS_COUNT    NUMBER,
    MERGED_ROWS   NUMBER,
    DELETED_ROWS  NUMBER,
    DURATION_SEC  NUMBER(12,3),
    STATUS        VARCHAR2(10) NOT NULL,        -- OK | SKIPPED | ERROR
    MESSAGE       VARCHAR2(2000),
    CONSTRAINT PK_C360_SYNC_LOG PRIMARY KEY (LOG_ID)
)
/
CREATE INDEX IX_C360_SYNC_LOG_T ON C360_SYNC_LOG (START_TIME)
/

