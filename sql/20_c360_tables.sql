-- 2. BẢNG MAP ĐỊA BÀN (phẳng, có PK) - làm mới bằng DELETE + INSERT trong 1 transaction
-------------------------------------------------------------------------------
CREATE TABLE C360_MAP_DBHC_TINH (
    MA_TINH_NGUON   VARCHAR2(3)   NOT NULL,   -- mã tỉnh đã chuẩn 3 số (kể cả mã cũ trước sáp nhập)
    MA_TINH         VARCHAR2(3),              -- tỉnh mới (NULL nếu MO_HO)
    TEN_TINH        VARCHAR2(200),
    NGUON_MAP       VARCHAR2(10)  NOT NULL,   -- HIEN_HANH | SAP_NHAP | MO_HO
    CONSTRAINT PK_C360_MAP_TINH PRIMARY KEY (MA_TINH_NGUON),
    CONSTRAINT CK_C360_MAP_TINH CHECK (NGUON_MAP IN ('HIEN_HANH','SAP_NHAP','MO_HO'))
)
/
CREATE TABLE C360_MAP_DBHC_XA (
    MA_XA_NGUON     VARCHAR2(5)   NOT NULL,   -- mã xã 5 số (hiện hành hoặc cũ)
    MA_XA           VARCHAR2(5),              -- xã mới (NULL nếu MO_HO)
    MA_TINH         VARCHAR2(3),              -- tỉnh của xã mới (MO_HO: giữ nếu các xã mới cùng 1 tỉnh)
    TEN_XA          VARCHAR2(200),
    TEN_TINH        VARCHAR2(200),
    NGUON_MAP       VARCHAR2(10)  NOT NULL,
    SO_XA_MOI       NUMBER(3)     NOT NULL,
    CONSTRAINT PK_C360_MAP_XA PRIMARY KEY (MA_XA_NGUON),
    CONSTRAINT CK_C360_MAP_XA CHECK (NGUON_MAP IN ('HIEN_HANH','SAP_NHAP','MO_HO'))
)
/

