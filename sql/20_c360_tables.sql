-- 6. API: KEY (chỉ lưu SHA-256) + AUDIT LOG
-------------------------------------------------------------------------------
CREATE TABLE C360_API_KEY (
    ID          NUMBER GENERATED ALWAYS AS IDENTITY,
    KEY_HASH    VARCHAR2(64)  NOT NULL,
    TEN_HE_THONG VARCHAR2(100) NOT NULL,
    SCOPES      VARCHAR2(200) NOT NULL,         -- lookup,batch,search,changes
    ACTIVE      NUMBER(1) DEFAULT 1 NOT NULL,
    CREATED_AT  DATE DEFAULT SYSDATE,
    CONSTRAINT PK_C360_API_KEY PRIMARY KEY (ID),
    CONSTRAINT UX_C360_API_KEY_HASH UNIQUE (KEY_HASH)
)
/
CREATE TABLE C360_API_AUDIT_LOG (
    ID          NUMBER GENERATED ALWAYS AS IDENTITY,
    LOG_TIME    TIMESTAMP DEFAULT SYSTIMESTAMP,
    KEY_NAME    VARCHAR2(100),
    ENDPOINT    VARCHAR2(60),
    PARAMS      VARCHAR2(1000),
    HTTP_STATUS NUMBER(3),
    RESULT_COUNT NUMBER,
    DURATION_MS NUMBER(10),
    CLIENT_IP   VARCHAR2(64),
    CONSTRAINT PK_C360_API_AUDIT PRIMARY KEY (ID)
)
/
CREATE INDEX IX_C360_API_AUDIT_T ON C360_API_AUDIT_LOG (LOG_TIME)
/
