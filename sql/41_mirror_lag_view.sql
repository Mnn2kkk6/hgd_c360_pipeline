CREATE OR REPLACE VIEW V_MIRROR_SYNC_LAG AS
SELECT MAX(SYNC_TS)                                           AS LAN_SYNC_CUOI,
       ROUND((SYSDATE - CAST(MAX(SYNC_TS) AS DATE)) * 86400)  AS GIAY_TU_LAN_SYNC_CUOI,
       COUNT(CASE WHEN SYNC_TS >= SYSDATE - 1/24 THEN 1 END)  AS SO_DONG_1H
FROM   MIRROR.VSS_HO_GD_NHANKHAU
/