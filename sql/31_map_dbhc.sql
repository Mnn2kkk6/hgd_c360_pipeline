-- Chạy bằng user C360. View danh mục địa bàn đang hiệu lực + tách MA_DBHC_SN + thủ tục làm mới 2 bảng Map.
-- Chịu được CẢ 2 dạng dữ liệu: file thật (tỉnh '01', MA_CHA='0003') và tài liệu yêu cầu (tỉnh '01TTT', MA_CHA NULL).

CREATE OR REPLACE VIEW C360_V_DBHC_TINH_HL AS
SELECT PKG_C360_UTIL.norm_tinh_key(d.MA_DBHC) AS MA_TINH,
       d.TEN                                   AS TEN_TINH,
       d.MA_DBHC_SN                            AS SN
FROM   MIRROR.VSS_DM_DBHC d
WHERE  d.TINH_TRANG = '1'
AND    (d.NGAY_HIEU_LUC     IS NULL OR d.NGAY_HIEU_LUC     <= SYSDATE)
AND    (d.NGAY_HET_HIEU_LUC IS NULL OR d.NGAY_HET_HIEU_LUC >  SYSDATE)
AND    (UPPER(TRIM(d.MA_DBHC)) LIKE '%TTT' OR LENGTH(TRIM(d.MA_DBHC)) <= 2)
AND    PKG_C360_UTIL.norm_tinh_key(d.MA_DBHC) IS NOT NULL
/
CREATE OR REPLACE VIEW C360_V_DBHC_XA_HL AS
SELECT TRIM(d.MA_DBHC)                          AS MA_XA,
       PKG_C360_UTIL.norm_tinh_key(d.MA_CHA)    AS MA_TINH,
       d.TEN                                    AS TEN_XA,
       d.MA_DBHC_SN                             AS SN
FROM   MIRROR.VSS_DM_DBHC d
WHERE  d.TINH_TRANG = '1'
AND    (d.NGAY_HIEU_LUC     IS NULL OR d.NGAY_HIEU_LUC     <= SYSDATE)
AND    (d.NGAY_HET_HIEU_LUC IS NULL OR d.NGAY_HET_HIEU_LUC >  SYSDATE)
AND    REGEXP_LIKE(TRIM(d.MA_DBHC), '^[0-9]{5}$')
/
-- Tách chuỗi MA_DBHC_SN ('00013;00004;00019') thành từng dòng (tối đa 50 mã/đơn vị). Chạy ở bước làm mới Map, KHÔNG chạy lúc join nhân khẩu.
CREATE OR REPLACE VIEW C360_V_SN_TINH AS
SELECT t.MA_TINH, t.TEN_TINH,
       PKG_C360_UTIL.norm_tinh_key(REGEXP_SUBSTR(t.SN, '[^;]+', 1, l.n)) AS MA_CU
FROM   C360_V_DBHC_TINH_HL t
JOIN  (SELECT LEVEL AS n FROM DUAL CONNECT BY LEVEL <= 50) l
  ON   l.n <= REGEXP_COUNT(t.SN, '[^;]+')
/
CREATE OR REPLACE VIEW C360_V_SN_XA AS
SELECT x.MA_XA, x.MA_TINH, x.TEN_XA,
       PKG_C360_UTIL.norm_xa_key(REGEXP_SUBSTR(x.SN, '[^;]+', 1, l.n)) AS MA_CU
FROM   C360_V_DBHC_XA_HL x
JOIN  (SELECT LEVEL AS n FROM DUAL CONNECT BY LEVEL <= 50) l
  ON   l.n <= REGEXP_COUNT(x.SN, '[^;]+')
/
CREATE OR REPLACE PROCEDURE PRC_REFRESH_MAP_DBHC IS
  v_t0   TIMESTAMP := SYSTIMESTAMP;
  v_tinh NUMBER;
  v_xa   NUMBER;
BEGIN
  -- DELETE + INSERT trong CÙNG 1 transaction, KHÔNG dùng TRUNCATE (DDL tự COMMIT & làm Map rỗng giữa chừng).
  -- Các CTE dùng MATERIALIZE: view danh mục gọi hàm PL/SQL nên phải tính MỘT lần, không để Oracle tính lại cho từng dòng NOT EXISTS.
  DELETE FROM C360_MAP_DBHC_TINH;
  DELETE FROM C360_MAP_DBHC_XA;

  INSERT INTO C360_MAP_DBHC_TINH (MA_TINH_NGUON, MA_TINH, TEN_TINH, NGUON_MAP)
  WITH ht AS (SELECT /*+ MATERIALIZE */ MA_TINH, TEN_TINH FROM C360_V_DBHC_TINH_HL),
       st AS (SELECT /*+ MATERIALIZE */ MA_TINH, TEN_TINH, MA_CU FROM C360_V_SN_TINH WHERE MA_CU IS NOT NULL),
       so AS (SELECT MA_TINH, TEN_TINH, MA_CU FROM st WHERE MA_CU NOT IN (SELECT MA_TINH FROM ht))
  SELECT MA_TINH, MA_TINH, TEN_TINH, 'HIEN_HANH' FROM ht
  UNION ALL
  SELECT MA_CU, MIN(MA_TINH), MIN(TEN_TINH), 'SAP_NHAP' FROM so GROUP BY MA_CU HAVING COUNT(DISTINCT MA_TINH) = 1
  UNION ALL
  SELECT MA_CU, NULL, NULL, 'MO_HO' FROM so GROUP BY MA_CU HAVING COUNT(DISTINCT MA_TINH) > 1;
  v_tinh := SQL%ROWCOUNT;

  INSERT INTO C360_MAP_DBHC_XA (MA_XA_NGUON, MA_XA, MA_TINH, TEN_XA, TEN_TINH, NGUON_MAP, SO_XA_MOI)
  WITH ht AS (SELECT /*+ MATERIALIZE */ MA_TINH, TEN_TINH FROM C360_V_DBHC_TINH_HL),
       hx AS (SELECT /*+ MATERIALIZE */ MA_XA, MA_TINH, TEN_XA FROM C360_V_DBHC_XA_HL),
       sx AS (SELECT /*+ MATERIALIZE */ MA_XA, MA_TINH, TEN_XA, MA_CU FROM C360_V_SN_XA WHERE MA_CU IS NOT NULL),
       so AS (SELECT sx.MA_XA, sx.MA_TINH, sx.TEN_XA, sx.MA_CU FROM sx WHERE sx.MA_CU NOT IN (SELECT MA_XA FROM hx))
  SELECT h.MA_XA, h.MA_XA, h.MA_TINH, h.TEN_XA, t.TEN_TINH, 'HIEN_HANH', 1
  FROM   hx h LEFT JOIN ht t ON t.MA_TINH = h.MA_TINH
  UNION ALL
  SELECT s.MA_CU, MIN(s.MA_XA), MIN(s.MA_TINH), MIN(s.TEN_XA), MIN(t.TEN_TINH), 'SAP_NHAP', 1
  FROM   so s LEFT JOIN ht t ON t.MA_TINH = s.MA_TINH
  GROUP  BY s.MA_CU
  HAVING COUNT(DISTINCT s.MA_XA) = 1
  UNION ALL
  -- MO_HO: không đoán MA_XA; giữ MA_TINH nếu các xã mới cùng 1 tỉnh
  SELECT s.MA_CU, NULL,
         CASE WHEN COUNT(DISTINCT s.MA_TINH) = 1 THEN MIN(s.MA_TINH) END,
         NULL,
         CASE WHEN COUNT(DISTINCT s.MA_TINH) = 1 THEN MIN(t.TEN_TINH) END,
         'MO_HO', COUNT(DISTINCT s.MA_XA)
  FROM   so s LEFT JOIN ht t ON t.MA_TINH = s.MA_TINH
  GROUP  BY s.MA_CU
  HAVING COUNT(DISTINCT s.MA_XA) > 1;
  v_xa := SQL%ROWCOUNT;

  INSERT INTO C360_SYNC_LOG (JOB_TYPE, START_TIME, END_TIME, MERGED_ROWS, DURATION_SEC, STATUS, MESSAGE)
  VALUES ('MAP', v_t0, SYSTIMESTAMP, v_tinh + v_xa,
          EXTRACT(SECOND FROM (SYSTIMESTAMP - v_t0)) + 60 * EXTRACT(MINUTE FROM (SYSTIMESTAMP - v_t0)),
          'OK', 'tinh=' || v_tinh || '; xa=' || v_xa);
  COMMIT;
EXCEPTION WHEN OTHERS THEN
  ROLLBACK;
  RAISE;
END;
/
