-- Chạy bằng user C360. Data Mart phục vụ 3 nhóm dashboard BI. Làm mới bằng PRC_REFRESH_DATAMART (Airflow DAG hgd_c360_maintenance chạy định kỳ).
-- Nhóm 1: nhân khẩu & định danh theo địa bàn
CREATE TABLE DM_NHANKHAU_DIABAN (
    MA_TINH            VARCHAR2(3),
    TEN_TINH           VARCHAR2(200),
    MA_XA              VARCHAR2(5),
    TEN_XA             VARCHAR2(200),
    NHOM_TUOI          VARCHAR2(12),
    GIOI_TINH          VARCHAR2(10),
    IS_ALIVE           VARCHAR2(10),
    SO_CONG_DAN        NUMBER NOT NULL,
    SO_CO_DINH_DANH    NUMBER NOT NULL
)
/
CREATE INDEX IX_DM_NK_TINH ON DM_NHANKHAU_DIABAN (MA_TINH)
/
-- Nhóm 2: chất lượng dữ liệu
CREATE TABLE DM_DQ_FLAG_TINH (
    FLAG_CODE    VARCHAR2(40) NOT NULL,
    MA_TINH      VARCHAR2(3),
    TEN_TINH     VARCHAR2(200),
    SO_BAN_GHI   NUMBER NOT NULL
)
/
CREATE TABLE DM_DQ_TINH (
    MA_TINH      VARCHAR2(3),
    TEN_TINH     VARCHAR2(200),
    TONG         NUMBER NOT NULL,
    SO_SACH      NUMBER NOT NULL,
    SO_LOI       NUMBER NOT NULL,
    TY_LE_LOI    NUMBER(7,4)
)
/
CREATE TABLE DM_DQ_TONG (
    FLAG_CODE    VARCHAR2(40) NOT NULL,
    NHOM         VARCHAR2(30),
    MO_TA        VARCHAR2(300),
    SO_BAN_GHI   NUMBER NOT NULL,
    TY_LE        NUMBER(7,4)
)
/
CREATE OR REPLACE VIEW V_DM_DINH_DANH_TINH AS
SELECT MA_TINH, TEN_TINH,
       SUM(SO_CONG_DAN)                                   AS TONG,
       SUM(SO_CO_DINH_DANH)                               AS CO_DINH_DANH,
       SUM(SO_CONG_DAN) - SUM(SO_CO_DINH_DANH)            AS CHUA_CO,
       ROUND(100 * SUM(SO_CO_DINH_DANH) / NULLIF(SUM(SO_CONG_DAN), 0), 2) AS TY_LE_CO_PCT
FROM   DM_NHANKHAU_DIABAN
GROUP  BY MA_TINH, TEN_TINH
/
-- Nhóm 3: giám sát vận hành đồng bộ (mỗi phút)
CREATE OR REPLACE VIEW V_SYNC_MONITOR AS
SELECT LOG_ID, TRUNC(START_TIME, 'MI') AS PHUT, START_TIME, JOB_TYPE, STATUS,
       KEYS_COUNT, MERGED_ROWS, DELETED_ROWS, QUEUE_ROWS, DURATION_SEC, MESSAGE
FROM   C360_SYNC_LOG
/
CREATE OR REPLACE VIEW V_SYNC_MONITOR_PHUT AS
SELECT TRUNC(START_TIME, 'MI')                    AS PHUT,
       SUM(KEYS_COUNT)                            AS SO_KHOA_BIEN_DONG,
       SUM(MERGED_ROWS)                           AS SO_DONG_MERGE,
       SUM(DELETED_ROWS)                          AS SO_DONG_DELETE,
       SUM(DURATION_SEC)                          AS THOI_GIAN_XU_LY_GIAY,
       SUM(CASE WHEN STATUS = 'ERROR' THEN 1 ELSE 0 END) AS SO_LO_LOI
FROM   C360_SYNC_LOG
WHERE  JOB_TYPE = 'NRT' AND STATUS <> 'SKIPPED'
GROUP  BY TRUNC(START_TIME, 'MI')
/
CREATE OR REPLACE VIEW V_QUEUE_BACKLOG AS
SELECT COUNT(*) AS SO_DONG_CHO, MIN(CREATED_AT) AS CU_NHAT FROM C360_QUEUE
/

CREATE OR REPLACE PROCEDURE PRC_REFRESH_DATAMART IS
  v_t0 TIMESTAMP := SYSTIMESTAMP;
  v_n  NUMBER;
BEGIN
  EXECUTE IMMEDIATE 'TRUNCATE TABLE DM_NHANKHAU_DIABAN';
  INSERT /*+ APPEND */ INTO DM_NHANKHAU_DIABAN
  SELECT c.MA_TINH, MAX(c.TEN_TINH), c.MA_XA, MAX(c.TEN_XA),
         CASE WHEN c.NGAY_SINH IS NULL THEN 'KHONG_RO'
              WHEN EXTRACT(YEAR FROM SYSDATE) - TO_NUMBER(SUBSTR(c.NGAY_SINH,1,4)) < 15 THEN '0-14'
              WHEN EXTRACT(YEAR FROM SYSDATE) - TO_NUMBER(SUBSTR(c.NGAY_SINH,1,4)) < 25 THEN '15-24'
              WHEN EXTRACT(YEAR FROM SYSDATE) - TO_NUMBER(SUBSTR(c.NGAY_SINH,1,4)) < 35 THEN '25-34'
              WHEN EXTRACT(YEAR FROM SYSDATE) - TO_NUMBER(SUBSTR(c.NGAY_SINH,1,4)) < 45 THEN '35-44'
              WHEN EXTRACT(YEAR FROM SYSDATE) - TO_NUMBER(SUBSTR(c.NGAY_SINH,1,4)) < 55 THEN '45-54'
              WHEN EXTRACT(YEAR FROM SYSDATE) - TO_NUMBER(SUBSTR(c.NGAY_SINH,1,4)) < 65 THEN '55-64'
              ELSE '65+' END AS NHOM_TUOI,
         CASE c.GIOI_TINH WHEN '1' THEN 'Nam' WHEN '2' THEN 'Nu' WHEN '0' THEN 'Nu' ELSE 'KHONG_RO' END,
         CASE c.IS_ALIVE WHEN '1' THEN 'CON_SONG' WHEN '0' THEN 'DA_MAT' ELSE 'KHONG_RO' END,
         COUNT(*),
         COUNT(c.SO_DINH_DANH)
  FROM   C360_THONG_TIN_CA_NHAN c
  GROUP  BY c.MA_TINH, c.MA_XA,
         CASE WHEN c.NGAY_SINH IS NULL THEN 'KHONG_RO'
              WHEN EXTRACT(YEAR FROM SYSDATE) - TO_NUMBER(SUBSTR(c.NGAY_SINH,1,4)) < 15 THEN '0-14'
              WHEN EXTRACT(YEAR FROM SYSDATE) - TO_NUMBER(SUBSTR(c.NGAY_SINH,1,4)) < 25 THEN '15-24'
              WHEN EXTRACT(YEAR FROM SYSDATE) - TO_NUMBER(SUBSTR(c.NGAY_SINH,1,4)) < 35 THEN '25-34'
              WHEN EXTRACT(YEAR FROM SYSDATE) - TO_NUMBER(SUBSTR(c.NGAY_SINH,1,4)) < 45 THEN '35-44'
              WHEN EXTRACT(YEAR FROM SYSDATE) - TO_NUMBER(SUBSTR(c.NGAY_SINH,1,4)) < 55 THEN '45-54'
              WHEN EXTRACT(YEAR FROM SYSDATE) - TO_NUMBER(SUBSTR(c.NGAY_SINH,1,4)) < 65 THEN '55-64'
              ELSE '65+' END,
         CASE c.GIOI_TINH WHEN '1' THEN 'Nam' WHEN '2' THEN 'Nu' WHEN '0' THEN 'Nu' ELSE 'KHONG_RO' END,
         CASE c.IS_ALIVE WHEN '1' THEN 'CON_SONG' WHEN '0' THEN 'DA_MAT' ELSE 'KHONG_RO' END;
  v_n := SQL%ROWCOUNT;
  COMMIT;

  EXECUTE IMMEDIATE 'TRUNCATE TABLE DM_DQ_FLAG_TINH';
  INSERT INTO DM_DQ_FLAG_TINH (FLAG_CODE, MA_TINH, TEN_TINH, SO_BAN_GHI)
  SELECT f.FLAG_CODE, c.MA_TINH, MAX(c.TEN_TINH), COUNT(*)
  FROM   C360_THONG_TIN_CA_NHAN c
  JOIN   C360_DQ_FLAG_DEF f ON INSTR(';' || c.DQ_FLAGS || ';', ';' || f.FLAG_CODE || ';') > 0
  WHERE  c.DQ_FLAGS IS NOT NULL
  GROUP  BY f.FLAG_CODE, c.MA_TINH;

  EXECUTE IMMEDIATE 'TRUNCATE TABLE DM_DQ_TINH';
  INSERT INTO DM_DQ_TINH (MA_TINH, TEN_TINH, TONG, SO_SACH, SO_LOI, TY_LE_LOI)
  SELECT c.MA_TINH, MAX(c.TEN_TINH), COUNT(*),
         SUM(CASE WHEN c.DQ_FLAGS IS NULL THEN 1 ELSE 0 END),
         SUM(CASE WHEN c.DQ_FLAGS IS NOT NULL THEN 1 ELSE 0 END),
         ROUND(SUM(CASE WHEN c.DQ_FLAGS IS NOT NULL THEN 1 ELSE 0 END) / COUNT(*), 4)
  FROM   C360_THONG_TIN_CA_NHAN c
  GROUP  BY c.MA_TINH;

  EXECUTE IMMEDIATE 'TRUNCATE TABLE DM_DQ_TONG';
  INSERT INTO DM_DQ_TONG (FLAG_CODE, NHOM, MO_TA, SO_BAN_GHI, TY_LE)
  SELECT f.FLAG_CODE, f.NHOM, f.MO_TA, NVL(s.N, 0),
         ROUND(NVL(s.N, 0) / NULLIF((SELECT COUNT(*) FROM C360_THONG_TIN_CA_NHAN), 0), 4)
  FROM   C360_DQ_FLAG_DEF f
  LEFT   JOIN (SELECT FLAG_CODE, SUM(SO_BAN_GHI) AS N FROM DM_DQ_FLAG_TINH GROUP BY FLAG_CODE) s
         ON s.FLAG_CODE = f.FLAG_CODE;
  INSERT INTO DM_DQ_TONG (FLAG_CODE, NHOM, MO_TA, SO_BAN_GHI, TY_LE)
  SELECT 'SACH_HOAN_TOAN', 'TONG', 'Bản ghi không dính cờ lỗi nào', NVL(SUM(SO_SACH), 0),
         ROUND(NVL(SUM(SO_SACH), 0) / NULLIF(SUM(TONG), 0), 4)
  FROM   DM_DQ_TINH;
  COMMIT;

  PRC_C360_LOG('DATAMART', 'OK', v_t0, p_msg => 'DM_NHANKHAU_DIABAN rows=' || v_n);
EXCEPTION WHEN OTHERS THEN
  DECLARE v_err VARCHAR2(2000) := SUBSTR(SQLERRM, 1, 2000);
  BEGIN
    ROLLBACK;
    PRC_C360_LOG('DATAMART', 'ERROR', v_t0, p_msg => v_err);
    RAISE;
  END;
END;
/
